let currentLang = 'ja';

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  currentLang = lang === 'en' ? 'en' : 'ja';
  try {
    localStorage.setItem('miyako_tsunami_lang', currentLang);
  } catch (e) {}
}

export function t(key) {
  const parts = key.split('.');
  let obj = translations[currentLang] || translations.ja;
  for (const p of parts) {
    if (!obj || obj[p] === undefined) return key;
    obj = obj[p];
  }
  return obj;
}

// Init from storage
try {
  const saved = localStorage.getItem('miyako_tsunami_lang');
  if (saved === 'en' || saved === 'ja') currentLang = saved;
} catch (e) {}
